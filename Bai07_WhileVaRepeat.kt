fun main() {

    // Đếm ngược từ 10 về 1 bằng while
    var so = 10

    while (so >= 1) {
        println(so)
        so--
    }

    repeat(5) {
        println("Thiện Tai")
    }

    // while dùng khi chưa biết chính xác số lần lặp,
    // repeat dùng khi biết trước số lần lặp.
}